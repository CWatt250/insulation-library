"""Generate app/src/sim/fittingsData.ts from research/fittings-verified.json.
    python3 tools/build_fittings.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
d = json.loads((ROOT / "research/fittings-verified.json").read_text())
el = {e["id"]: e for e in d["equivalent_lengths"]}
et = el["EL-ILTRM-elbow-tee"]["rows"]
areas = None
def walk(o):
    global areas
    if isinstance(o, dict):
        if "bare_surface_areas_valves_flanges" in o:
            areas = o["bare_surface_areas_valves_flanges"]
        for v in o.values():
            walk(v)
    elif isinstance(o, list):
        for v in o:
            walk(v)
walk(d)
doe = d["valve_cover_savings"]["doe_steam_tip_17_2004_2006_2012"]

def nps_val(s):
    return sum((lambda a, b=None: a / b if b else a)(*map(float, p.split("/"))) for p in s.split("-"))

lines = [
    "// Generated by tools/build_fittings.py from research/fittings-verified.json — do not edit by hand.",
    "",
    "/** Illinois TRM (F12/F13): 90° elbow and straight tee as feet of same-NPS straight pipe, surface-area basis. */",
    "export const ELBOW_TEE_FT: { nps: number; elbow: number; tee: number }[] = [",
]
for r in et:
    lines.append(f"  {{ nps: {nps_val(r['nps'])}, elbow: {r['elbow_90_ft']}, tee: {r['tee_straight_ft']} }},")
lines += ["]", "", "/** ASTM C1129-12 bare surface areas, ANSI class 150, ft² (as tabulated by the Illinois TRM, F12/F13). */",
          "export const VALVE_FT2_150: { nps: number; ft2: number }[] = ["]
for r in areas["valves"]:
    lines.append(f"  {{ nps: {nps_val(r['nps'])}, ft2: {r['class_150_ft2']} }},")
lines += ["]", "export const FLANGE_FT2_150: { nps: number; ft2: number }[] = ["]
for r in areas["flanges"]:
    lines.append(f"  {{ nps: {nps_val(r['nps'])}, ft2: {r['class_150_ft2']} }},")
lines += ["]", "", "/** DOE Steam Tip Sheet #17 (F1): savings from a removable insulated valve cover, Btu/hr. 1\" pad, class 150 flanged valve, 65°F ambient, still air. */",
          "export const DOE_VALVE_SAVINGS: { tempF: number; byNps: Record<number, number> }[] = ["]
for r in doe["rows"]:
    by = {int(k.split("_")[1].replace("in", "")): v for k, v in r.items() if k.startswith("valve_")}
    lines.append(f"  {{ tempF: {r['operating_temperature_F']}, byNps: {json.dumps(by)} }},")
lines.append("]")
(ROOT / "app/src/sim/fittingsData.ts").write_text("\n".join(lines) + "\n")
print("ok", len(et), len(areas["valves"]), len(areas["flanges"]), len(doe["rows"]))
