"""Generate app/src/data/wsecData.ts from research/wsec-verified.json (2021 WSEC,
WAC 51-11C / 51-11R, in effect since 3/15/2024). Nothing is retyped by hand.
    python3 tools/build_wsec.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
W = json.loads((ROOT / "research/wsec-verified.json").read_text())

counties = W["climate_zones"]["counties"]
assert len(counties) == 39 and {c["zone"] for c in counties} == {"4C", "5B"}

tbl = W["pipe_commercial"]["table"]
cols = ["< 1", "1 to < 1-1/2", "1-1/2 to < 4", "4 to < 8", "≥ 8"]
rows = []
for r in tbl["rows"]:
    lo, hi = r["fluid_min_F"], r["fluid_max_F"]
    rows.append((lo, hi, r["k_min"], r["k_max"], r["mean_rating_temp_F"], [r["thickness_in"][c] for c in cols], r["fluid_range_F_as_served"].replace("˃", ">")))

duct = {r["id"]: r for r in W["duct_commercial"]["rows"]}

def R(i):
    v = duct[i]["R"]
    return "null" if v is None else f"{v:g}"

out = [
    "// GENERATED by tools/build_wsec.py from research/wsec-verified.json — do not edit.",
    "",
    "/** Washington counties and their WSEC climate zone (Table C301.1 / R301.1) [W3, W4]. */",
    "export const WA_COUNTIES: { county: string; zone: '4C' | '5B' }[] = [",
    *[f"  {{ county: {json.dumps(c['county'])}, zone: '{c['zone']}' }}," for c in counties],
    "]",
    "",
    "/** WSEC-C Table C403.10.3 minimum pipe insulation thickness [W5]: fluid range, k range, mean rating °F, inches by NPS column. */",
    "export const WSEC_PIPE: { lo: number | null; hi: number | null; k: [number, number]; meanF: number; t: [number, number, number, number, number]; label: string }[] = [",
    *[f"  {{ lo: {json.dumps(lo)}, hi: {json.dumps(hi)}, k: [{k0:g}, {k1:g}], meanF: {m}, t: [{', '.join(f'{x:g}' for x in t)}], label: {json.dumps(lab + '°F')} }}," for lo, hi, k0, k1, m, t, lab in rows],
    "]",
    "",
    "/** WSEC-C C403.10.1 duct insulation R-values by row id [W5] (4C, 5B). */",
    "export const WSEC_DUCT_R = {",
    f"  outsideSupplyReturn: {{ '4C': {R('WD-7')}, '5B': {R('WD-8')} }},",
    f"  unconditioned: {{ '4C': {R('WD-9')}, '5B': {R('WD-10')} }},",
    f"  unconditionedSmallDT: {{ '4C': {R('WD-11')}, '5B': {R('WD-12')} }},",
    f"  envelopeAssembly: {{ '4C': {R('WD-13')}, '5B': {R('WD-14')} }},",
    f"  supplyConditioned: {{ '4C': {R('WD-15')}, '5B': {R('WD-16')} }},",
    f"  afterEnergyRecovery: {{ '4C': {R('WD-21')}, '5B': {R('WD-22')} }},",
    f"  exhaustAfterDamper: {{ '4C': {R('WD-23')}, '5B': {R('WD-24')} }},",
    f"  outdoorAirBeforeDamper: {{ '4C': {R('WD-1')}, '5B': {R('WD-2')} }},",
    f"  outdoorAirAfterDamper: {{ '4C': {R('WD-3')}, '5B': {R('WD-4')} }},",
    f"  outdoorAirSmallUnit: {{ '4C': {R('WD-5')}, '5B': {R('WD-6')} }},",
    "}",
    "",
]
(ROOT / "app/src/data/wsecData.ts").write_text("\n".join(out))
print("counties", len(counties), "| pipe rows", len(rows), "| duct", {k: duct[k]["R"] for k in ["WD-1", "WD-3", "WD-5", "WD-7", "WD-8", "WD-9", "WD-11", "WD-15", "WD-21", "WD-23"]})
