"""Generate app/src/data/pipeWalls.ts from research/pipe-materials-verified.json.

Copper Type L walls (CDA Copper Tube Handbook, G1), PVC Schedule 40 OD and
minimum wall (ASTM D1785 per Charlotte G3, Spears G5, IPEX G6), PVC thermal
conductivity and maximum service temperature. Nothing is retyped by hand.
    python3 tools/build_pipes.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
d = json.loads((ROOT / "research/pipe-materials-verified.json").read_text())
steel = re.findall(r"\{ nps: '([^']+)', od:", (ROOT / "app/src/data/pipe.ts").read_text())

tl = d["copper"]["type_l"]
copper = {r["nominal_in"]: r["wall_in"] for r in tl["rows"]}

pvc = {}
split = []
for r in d["pvc"]["schedule_40"]["rows"]:
    if r["nps"] not in steel:
        continue
    w = r.get("min_wall_in")
    if not isinstance(w, (int, float)):
        # sources differ by 0.001 in.: take the value two of the three manuals print
        votes = [v["min_wall_in"] for v in r["by_source"].values() if isinstance(v.get("min_wall_in"), (int, float))]
        w = max(set(votes), key=votes.count)
        assert votes.count(w) >= 2, r["nps"]
        split.append(f'{r["nps"]}: {w:g} ({", ".join(f"{k} {v['min_wall_in']:g}" for k, v in r["by_source"].items())})')
    pvc[r["nps"]] = (r["od_in"], w)
missing = [n for n in steel if n not in pvc]

# PVC k: Charlotte (G3) and IPEX (G6) both print 1.2 Btu·in/(hr·ft²·°F), ASTM C177; Spears (G5) prints 1.02
ks = [v for v in d["pvc"]["thermal_conductivity"]["values"] if v["material"] == "PVC"]
k12 = [v for v in ks if v["value"] == 1.2]
assert {s for v in k12 for s in v["src"]} >= {"G3", "G6"}, "PVC k = 1.2 not found in G3 and G6"
k_other = sorted({(v["value"], v["src"][0]) for v in ks if v["value"] != 1.2})

maxq = [q for q in d["pvc"]["max_service_temperature"] if q["quote"].strip() == "PVC 140"]
assert maxq and maxq[0]["src"] == ["G3"], "PVC 140°F limit not found"

def num(x):
    return f"{x:g}"

out = [
    "// GENERATED by tools/build_pipes.py from research/pipe-materials-verified.json — do not edit.",
    "",
    "/** Copper tube Type L wall (in.) by nominal size: CDA Copper Tube Handbook Table 14.2b [G1]. */",
    "/** PVC Schedule 40 OD and minimum wall (in.) per ASTM D1785: Charlotte TM-PL [G3], Spears IP-4 [G5], IPEX Vol. I [G6]. */",
    *[f"// two of three agree — {x}" for x in split],
    "export const PIPE_WALLS: { copperL: Record<string, number>; pvc40: Record<string, { od: number; wall: number }> } = {",
    "  copperL: { " + ", ".join(f"'{k}': {num(v)}" for k, v in copper.items()) + " },",
    "  pvc40: {",
    *[f"    '{k}': {{ od: {num(o)}, wall: {num(w)} }}," for k, (o, w) in pvc.items()],
    "  },",
    "}",
    "",
    "/** Published maximum service temperature (pressure pipe) [G3 p. 29: \"PVC 140\"]. */",
    "export const PIPE_LIMITS: Partial<Record<'steel' | 'copper' | 'pvc', { label: string; maxF: number; src: string[] }>> = {",
    "  pvc: { label: 'PVC pipe', maxF: 140, src: ['G3'] },",
    "}",
    "",
    "/**",
    " * Pipe-wall conduction. Plastic walls are included (constant k); metal walls are",
    " * neglected, as C680-style calculations start from the bare pipe surface temperature.",
    " * PVC: 1.2 Btu·in/(hr·ft²·°F), ASTM C177, Charlotte [G3] and IPEX [G6]"
    + "".join(f"; Spears [{s}] prints {v:g}" for v, s in k_other) + ".",
    " */",
    "export const PIPE_PROPS: Partial<Record<'steel' | 'copper' | 'pvc', { wallKWmK?: number; kIp?: number; src: string[] }>> = {",
    "  pvc: { kIp: 1.2, wallKWmK: 1.2 * 0.144227888, src: ['G3', 'G6'] },",
    "}",
    "",
]
(ROOT / "app/src/data/pipeWalls.ts").write_text("\n".join(out))
print(f"copper L: {len(copper)} sizes; PVC Sch 40: {len(pvc)} sizes; steel NPS without PVC data: {missing}")
